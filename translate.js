  let currentLang = localStorage.getItem('portfolio_lang') || 'pt';
  window.translations = translations;
  window.currentLang = currentLang;

  function setLanguage(lang) {
    if (!translations[lang]) lang = 'pt';
    currentLang = lang;
    window.currentLang = lang;
    localStorage.setItem('portfolio_lang', lang);
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;

    const t = translations[lang];

    // Atualiza todos os nós de texto com data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) el.textContent = t[key];
    });

    // Atualiza placeholders dos inputs
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (t[key]) el.setAttribute('placeholder', t[key]);
    });

    // Atualiza texto do botão do dropdown
    const langBtnText = document.getElementById('current-lang-text');
    if (langBtnText) {
      langBtnText.textContent = t.lang_btn;
    }

    // Atualiza classe ativa no dropdown
    const langOptions = document.querySelectorAll('.lang-opt');
    langOptions.forEach(opt => {
      opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });

    // Atualiza texto do botão Modo Claro / Escuro
    if (typeof updateThemeButtonText === 'function') {
      updateThemeButtonText();
    } else if (typeof window.updateThemeButtonText === 'function') {
      window.updateThemeButtonText();
    }

    // Re-renderiza os cards de repositórios dinâmicos no novo idioma
    const repos = window.cachedGithubRepos;
    if (repos && repos.length > 0) {
      if (typeof renderProjectCards === 'function') {
        renderProjectCards(repos);
      } else if (typeof window.renderProjectCards === 'function') {
        window.renderProjectCards(repos);
      }
    }
  }

  window.setLanguage = setLanguage;

  document.addEventListener('DOMContentLoaded', () => {
    const langBtn = document.getElementById('lang-btn');
    const langDropdown = document.getElementById('lang-dropdown');
    const langOptions = document.querySelectorAll('.lang-opt');

    if (langBtn && langDropdown) {
      langBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        langDropdown.classList.toggle('show');
      });

      document.addEventListener('click', (e) => {
        if (!langDropdown.contains(e.target) && e.target !== langBtn) {
          langDropdown.classList.remove('show');
        }
      });

      langOptions.forEach(opt => {
        opt.addEventListener('click', () => {
          const selected = opt.getAttribute('data-lang');
          setLanguage(selected);
          langDropdown.classList.remove('show');
        });
      });
    }

    setLanguage(currentLang);
  });
